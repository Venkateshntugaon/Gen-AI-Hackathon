"""Saves real prompts and Gemini responses to docs/prompt_samples.md for the Review 2 report.

It runs the four LLM steps (extract, judge, generate, verify) on 2 questions from the
sample paper and writes, for each step, the exact prompt sent, the input data and
the raw JSON that Gemini returned. Cached replies are reused, so re-running is free.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.reviewer import config, llm
from src.reviewer.ingest.llm_extract import PROMPT_FILE as EXTRACT_PROMPT, ExtractOutput
from src.reviewer.models import MCQ
from src.reviewer.pipeline.generator import GenerateOutput
from src.reviewer.pipeline.judge import JudgeOutput
from src.reviewer.pipeline.rules import check_rules
from src.reviewer.pipeline.runner import weak_distractors
from src.reviewer.pipeline.judge import merge_findings, verdict_to_findings
from src.reviewer.pipeline.similarity import check_similarity
from src.reviewer.pipeline.validator import VerifyItem

OUTPUT = ROOT / "docs" / "prompt_samples.md"

# Q4 (implausible "A bicycle") and Q7 ("Steam" is also correct) from data/sample/sample_paper.docx
SAMPLE_TEXT = """4. What is the part of the flower that produces pollen?
A) A bicycle   B) Stamen   C) Stigma   D) Leaves
7. The addition of heat changes liquid water to what?
A) Steam   B) Ice   C) Water vapor   D) Distilled water"""

SAMPLES = [
    MCQ(id="Q4", question="What is the part of the flower that produces pollen?", correct_answer="Stamen",
        distractors=["A bicycle", "Stigma", "Leaves"], source="sample_paper.docx Q4"),
    MCQ(id="Q7", question="The addition of heat changes liquid water to what?", correct_answer="Water vapor",
        distractors=["Steam", "Ice", "Distilled water"], source="sample_paper.docx Q7"),
]


def section(title: str, prompt: str, payload, raw: str) -> str:
    pretty = json.dumps(json.loads(raw), indent=2, ensure_ascii=False)
    payload_text = payload if isinstance(payload, str) else json.dumps(payload, indent=2, ensure_ascii=False)
    return (f"### {title}\n\n**Input**\n\n```\n{payload_text}\n```\n\n"
            f"**Exact prompt sent**\n\n```\n{prompt}\n```\n\n"
            f"**Raw JSON response**\n\n```json\n{pretty}\n```\n")


def capture_extract() -> str:
    prompt = f"{EXTRACT_PROMPT.read_text(encoding='utf-8')}\n\nDocument:\n{SAMPLE_TEXT}"
    raw = llm.generate_text(prompt, ExtractOutput, temperature=0.0)
    return section("Extract (fallback extractor, temperature 0)", prompt, SAMPLE_TEXT, raw)


def capture_question(mcq: MCQ) -> list[str]:
    parts = []
    rule_findings = check_rules(mcq)
    sim_findings, scores = check_similarity(mcq)

    judge_payload = {
        "question": mcq.question, "correct_answer": mcq.correct_answer,
        "distractors": {str(i): d for i, d in enumerate(mcq.distractors)},
        "rule_flags": [f"{f.target}: {f.issue_type}" for f in rule_findings] or "none",
        "similarity_scores": scores,
    }
    prompt, raw = llm.call_raw("judge", judge_payload, JudgeOutput, temperature=0.2)
    parts.append(section(f"Judge — {mcq.id} (temperature 0.2)", prompt, judge_payload, raw))

    llm_findings = verdict_to_findings(JudgeOutput.model_validate_json(raw), len(mcq.distractors))
    weak = weak_distractors(merge_findings(rule_findings + sim_findings + llm_findings))
    if not weak:
        return parts
    gen_payload = {
        "question": mcq.question, "correct_answer": mcq.correct_answer,
        "kept_options": [d for i, d in enumerate(mcq.distractors) if i not in weak] or "none",
        "weak_distractors": {str(i): f"{mcq.distractors[i]} ({p})" for i, p in weak.items()},
        "rejected": "none",
    }
    prompt, raw = llm.call_raw("generate", gen_payload, GenerateOutput, temperature=0.7)
    parts.append(section(f"Generate — {mcq.id} (temperature 0.7)", prompt, gen_payload, raw))

    candidates = [c.text for r in GenerateOutput.model_validate_json(raw).replacements for c in r.candidates]
    verify_payload = {"question": mcq.question, "candidates": {str(i): t for i, t in enumerate(candidates)}}
    prompt, raw = llm.call_raw("verify", verify_payload, list[VerifyItem], temperature=0.0)
    parts.append(section(f"Verify — {mcq.id} (temperature 0)", prompt, verify_payload, raw))
    return parts


def main() -> None:
    parts = [
        "# Prompt samples",
        "",
        f"Generated by `scripts/capture_prompt_samples.py` with model `{config.GEMINI_MODEL}`. "
        "Each section shows the input, the exact prompt sent to Gemini and its raw JSON reply. "
        "All calls use `response_mime_type=\"application/json\"` with a Pydantic `response_schema`.",
        "",
        "Questions used: Q4 (planted implausible option \"A bicycle\") and Q7 (planted also-correct "
        "option \"Steam\") from `data/sample/sample_paper.docx`.",
        "",
        capture_extract(),
    ]
    for mcq in SAMPLES:
        parts.extend(capture_question(mcq))
    OUTPUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"Saved {OUTPUT}")


if __name__ == "__main__":
    main()
